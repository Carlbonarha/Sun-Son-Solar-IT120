    <script>
        const quoteForm = document.getElementById('quoteForm');
        const quoteMessage = document.getElementById('quoteMessage');
        const submitQuote = document.getElementById('submitQuote');

        quoteForm.addEventListener('submit', async event => {
            event.preventDefault();
            quoteMessage.textContent = '';
            quoteMessage.removeAttribute('data-state');
            submitQuote.disabled = true;
            try {
                const response = await fetch('<?= site_url('quote-requests') ?>', {
                    method: 'POST',
                    headers: { 'X-Requested-With': 'XMLHttpRequest' },
                    body: new FormData(quoteForm)
                });
                const result = await response.json();
                if (!response.ok || !result.success) {
                    throw new Error(result.error || 'The request could not be submitted.');
                }
                quoteMessage.dataset.state = 'success';
                quoteMessage.textContent = 'Your request was submitted successfully.';
                quoteForm.reset();
            } catch (error) {
                quoteMessage.dataset.state = 'error';
                quoteMessage.textContent = error instanceof Error ? error.message : 'The request could not be submitted.';
            } finally {
                submitQuote.disabled = false;
            }
        });
    </script>
